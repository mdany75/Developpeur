/// Mots-clés proposés d'après ce que voit Vision (`VNClassifyImageRequest`, sur ce Mac, sans
/// réseau), traduits en français : Vision ne nomme qu'en anglais, parmi 1303 étiquettes
/// (relevées sous macOS 26 : `supportedIdentifiers`), du plus large (« animal ») au plus précis
/// (« beagle »). Seules les étiquettes sûres sont gardées (précision de 90 % pour un rappel d'au
/// moins 1 %, le filtre que conseille Apple), sans les plus générales, qui ne servent pas de
/// mots-clés à un photographe.
public enum MotsClesVision {
    public struct Proposition: Equatable {
        public var mot: String
        public var etiquette: String
        public var confiance: Double
    }

    /// Étiquettes trop générales pour un mot-clé (ou des catégories fourre-tout).
    static let generiques: Set<String> = [
        "adult", "animal", "art", "arthropods", "cake_regular", "candy_other", "canine", "celestial_body", "celestial_body_other",
        "chair_other", "clothing", "consumer_electronics", "container", "conveyance", "daytime", "decoration", "document",
        "domicile", "feline", "food", "footwear", "frame", "furniture", "games", "glove_other", "headgear", "housewares",
        "illustrations", "interior_room", "land", "light", "liquid", "machine", "mammal", "material", "media", "optical_equipment", "outdoor",
        "people", "plant", "printed_page", "raw_glass", "recreation", "road_other", "snake_other", "sport", "structure",
        "textile", "tool", "ungulates", "utensil", "vehicle", "wood_processed",
    ]

    /// Mots-clés proposés pour une image : au plus `maximum`, du plus sûr au moins sûr, sans
    /// doublon de traduction. Vide si Vision échoue.
    public static func proposer(_ image: CGImage, maximum: Int = 6) -> [Proposition] {
        let request = VNClassifyImageRequest()
        guard (try? VNImageRequestHandler(cgImage: image, options: [:]).perform([request])) != nil else { return [] }
        let sures = (request.results ?? []).filter { $0.confidence >= 0.1 && $0.hasMinimumRecall(0.01, forPrecision: 0.9) }
        return choisir(sures.map { ($0.identifier, Double($0.confidence)) }, maximum: maximum)
    }

    /// Les étiquettes retenues, triées par confiance, traduites, sans les générales ni les doublons.
    static func choisir(_ etiquettes: [(String, Double)], maximum: Int) -> [Proposition] {
        var vus = Set<String>()
        var resultat: [Proposition] = []
        for (etiquette, confiance) in etiquettes.sorted(by: { $0.1 > $1.1 }) where !generiques.contains(etiquette) {
            let mot = traduction(etiquette)
            guard vus.insert(mot).inserted else { continue }
            resultat.append(Proposition(mot: mot, etiquette: etiquette, confiance: confiance))
            if resultat.count >= maximum { break }
        }
        return resultat
    }

    /// Le mot français d'une étiquette de Vision (l'étiquette elle-même, sans « _ », si la table
    /// ne la connaît pas : une version future de macOS peut en ajouter).
    public static func traduction(_ etiquette: String) -> String {
        traductions[etiquette] ?? etiquette.replacingOccurrences(of: "_", with: " ")
    }

    /// Les étiquettes anglaises de Vision qui se traduisent par ce mot (casse indifférente), pour
    /// les synonymes d'un mot-clé créé : une recherche en anglais le trouve aussi.
    public static func synonymesAnglais(_ mot: String) -> [String] {
        let voulu = mot.trimmingCharacters(in: .whitespaces).lowercased()
        guard !voulu.isEmpty else { return [] }
        return traductions.filter { $0.value.lowercased() == voulu }.keys
            .map { $0.replacingOccurrences(of: "_", with: " ") }
            .filter { $0.lowercased() != voulu }
            .sorted()
    }

    static let traductions: [String: String] = {
        var table: [String: String] = [:]
        for ligne in source.split(separator: "\n") {
            let parties = ligne.split(separator: "=", maxSplits: 1)
            if parties.count == 2 { table[String(parties[0])] = String(parties[1]) }
        }
        return table
    }()

